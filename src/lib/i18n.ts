// Minimal i18n: only English and Spanish. The active language comes from
// [app] language in config.toml (editable in Settings); on first install the
// backend picks it from the OS locale (es → Spanish, anything else → English).
import { useStore } from "../state/store";

export type Lang = "en" | "es";

export function normLang(l: string | null | undefined): Lang {
  return l && l.toLowerCase().startsWith("es") ? "es" : "en";
}

