export const dict: Record<Lang, Record<string, string>> = { en, es };

export function t(lang: Lang, key: string, params?: Record<string, string | number>): string {
  let s = dict[lang][key] ?? dict.en[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** Bound translator for the current configured language. */
export function useT() {
  const lang = normLang(useStore((s) => s.config?.app.app.language));
  return (key: string, params?: Record<string, string | number>) => t(lang, key, params);
}
